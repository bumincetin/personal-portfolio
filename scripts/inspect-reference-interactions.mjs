import { chromium } from 'playwright';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto('https://basement.studio',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(4000);
const log=[];
log.push({state:'home',buttons:await page.locator('button').allTextContents(),links:await page.locator('a').evaluateAll(a=>a.map(e=>({text:e.textContent,href:e.getAttribute('href')})))});
await page.mouse.move(1100,450); await page.waitForTimeout(800);
await page.screenshot({path:'artifacts/redesign/reference/pointer.png',timeout:20000});
const services=page.getByRole('link',{name:'Services',exact:true}).first();
await services.click(); await page.waitForTimeout(1800);
await page.screenshot({path:'artifacts/redesign/reference/services.png',timeout:20000});
log.push({state:'services',url:page.url(),text:await page.locator('body').innerText()});
await page.goBack(); await page.waitForTimeout(1000);
const contact=page.getByText('Contact Us',{exact:true}).first();
await contact.click(); await page.waitForTimeout(1200);
await page.screenshot({path:'artifacts/redesign/reference/contact.png',timeout:20000});
log.push({state:'contact',url:page.url(),text:await page.locator('body').innerText()});
await page.setViewportSize({width:393,height:852}); await page.goto('https://basement.studio',{waitUntil:'domcontentloaded'}); await page.waitForTimeout(1500);
log.push({state:'mobile',buttons:await page.locator('button').evaluateAll(b=>b.map(e=>({text:e.textContent,aria:e.getAttribute('aria-label')})))});
fs.writeFileSync('artifacts/redesign/reference/interactions.json',JSON.stringify(log,null,2));
await browser.close();
